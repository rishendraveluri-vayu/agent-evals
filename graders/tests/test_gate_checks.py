"""The provenance and required_tools graders on the runner's real checks.json.

The fixtures in fixtures/gate-20261104/ are the out/ files of gate runs against the fake model
(no real model), through the own loop and Hermes, regenerated by fixtures/make_gate_fixtures.py.
Each task listed required_tools; the runner wrote checks.json:

- `*-emi` (fake script finance-emi): "about Rs 8,997 a month ... about Rs 11.59 lakh", both from
  calculate_emi's result; required_tools [calculate_emi].
- `*-emi-unsupported` (finance-emi-unsupported): adds "about Rs 1,07,967 a year", worked out in
  the reply (8,997.26 x 12), which no tool returned; required_tools [calculate_emi, list_debts],
  and list_debts was never called.

fixtures/gate-20261105/ (D54, the arithmetic tools), the same way, on the toolset with 18 tools:

- `*-sum-tool` (finance-sum-tool): calculate_emi, list_debts, then `add` of the EMI and the
  minimums, and an answer stating Rs 8,997.26, Rs 18,332.50 and their sum Rs 27,329.76.
- `*-sum-unsupported` (finance-sum-unsupported): the same answer word for word, without the `add`
  call: the sum is worked out in the reply, as Hermes did on 4 Nov.
- `*-sum-laundered` (finance-sum-laundered, D56): the same answer again, with the sum worked out
  in the reply and passed through `round`, which returns it unchanged.

The gate-20261105 folder was regenerated after D56 (runner 0.2.0), so its checks.json has
`arithmetic`; gate-20261104's were written before it and keep the older shape.

fixtures/gate-20261105-d58/ (D58, runner 0.3.0, toolset v3 with 19 tools), the same way:

- `*-yearly-tool` (finance-yearly-tool): calculate_emi, then `multiply([8997.26, 12])`, and an
  answer stating the EMI and the yearly Rs 1,07,967.12; 12 is a unit fact.
- `*-rate-tool` (finance-rate-tool): get_client_profile, `reference_rates`, then
  `percent_of(92500, 6.25)`: a year's FD interest on Meera's monthly income at SBI's rate.
- `*-rate-made-up` (finance-rate-made-up): the same kind of answer at 7.4%, a rate no tool
  returned, without calling reference_rates.

fixtures/gate-20261105-d61/ (D61, runner 0.4.0: verify, don't trace), the same way:

- `*-sum-tool` (finance-sum-tool): the sum from `add`, verified as `tool`.
- `*-sum-prose` (finance-sum-unsupported): the same answer with the sum worked out in the reply;
  the checker recomputes it, so it is verified as `derived_in_prose`.
- `*-sum-wrong` (finance-sum-wrong): the same answer with the sum worked out wrong (27,392.76).

The older folders keep the checks.json their runner wrote; a regrade never re-runs the checks.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import jsonschema
import pytest

from evals_graders.graders import grade_trial
from evals_graders.trial import TrialView

GATE = Path(__file__).parent / "fixtures" / "gate-20261104"
ARITHMETIC = Path(__file__).parent / "fixtures" / "gate-20261105"
D58 = Path(__file__).parent / "fixtures" / "gate-20261105-d58"
D61 = Path(__file__).parent / "fixtures" / "gate-20261105-d61"
REPO = Path(__file__).resolve().parents[2]
CHECKS_SCHEMA = REPO / "contract" / "v2" / "checks.schema.json"
HARNESSES = ("ownloop", "hermes")
PROVENANCE = {"id": "every-amount-from-a-tool", "type": "provenance"}
REQUIRED = {"id": "required-tools", "type": "required_tools"}


def grades(name: str, *specs: dict) -> list[dict]:
    return grade_trial(GATE / name, list(specs))["grades"]


@pytest.mark.parametrize(
    "folder",
    sorted(p for root in (GATE, ARITHMETIC, D58, D61) for p in root.iterdir() if p.is_dir()),
    ids=lambda p: f"{p.parent.name}/{p.name}",
)
def test_the_fixtures_are_the_contracts_checks(folder):
    checks = json.loads((folder / "checks.json").read_text(encoding="utf-8"))
    schema = json.loads(CHECKS_SCHEMA.read_text(encoding="utf-8"))
    assert list(jsonschema.Draft202012Validator(schema).iter_errors(checks)) == []
    report = json.loads((folder / "runner-report.json").read_text(encoding="utf-8"))
    assert report["checks"]["path"] == "checks.json" and report["checks"]["valid"] is True


@pytest.mark.parametrize("harness", HARNESSES)
def test_a_fully_supported_answer_passes(harness):
    prov, req = grades(f"{harness}-emi", PROVENANCE, REQUIRED)
    assert prov["verdict"] == "pass", prov
    assert prov["reason"].startswith("0 of 2 amount(s)")
    assert req["verdict"] == "pass", req
    assert req["reason"] == "every required tool was called: calculate_emi"
    # The evidence is the call itself, quoted from the span, whatever the harness named it.
    assert [e["tool"] for e in req["evidence"]] == ["calculate_emi"]
    assert '"principal"' in req["evidence"][0]["quote"]


@pytest.mark.parametrize("harness", HARNESSES)
def test_an_unsupported_figure_and_a_missing_tool_fail(harness):
    name = f"{harness}-emi-unsupported"
    prov, req = grades(name, PROVENANCE, REQUIRED)
    assert prov["verdict"] == "fail", prov
    assert "1 of 3 amount(s)" in prov["reason"] and "Rs 1,07,967" in prov["reason"]
    assert prov["evidence"] == [{"source": "final_answer", "quote": "Rs 1,07,967"}]
    # Every quote is verbatim in the final answer.
    final = TrialView.load(GATE / name).final_answer
    assert all(e["quote"] in final for e in prov["evidence"])
    loose = grades(name, {**PROVENANCE, "max_unsupported": 1})[0]
    assert loose["verdict"] == "pass"
    assert req["verdict"] == "fail", req
    assert "list_debts" in req["reason"] and "called: calculate_emi" in req["reason"]


def test_tool_called_is_the_other_path_to_the_same_fact():
    """tool_called reads the spans itself and can check arguments; required_tools reads the
    platform's record. On the same trial they agree that list_debts was never called."""
    tool, req = grades(
        "ownloop-emi-unsupported",
        {"id": "debts", "type": "tool_called", "tool": "list_debts"},
        REQUIRED,
    )
    assert tool["verdict"] == req["verdict"] == "fail"
    args = grades(
        "hermes-emi-unsupported",
        {
            "id": "emi-args",
            "type": "tool_called",
            "tool": "calculate_emi",
            "args": {"principal": 1000000, "tenure_months": 240},
        },
    )[0]
    assert args["verdict"] == "pass", args


@pytest.mark.parametrize("harness", HARNESSES)
def test_a_sum_from_add_passes_and_the_same_sum_without_it_fails(harness):
    """D54: the same answer, Rs 8,997.26 + Rs 18,332.50 = Rs 27,329.76, through the real runner
    and adapter on the fake model. With the `add` call every amount has a tool behind it and
    provenance passes; without it the sum is the agent's own arithmetic and provenance fails on
    exactly that amount."""
    tool_dir, prose_dir = (
        ARITHMETIC / f"{harness}-sum-tool",
        ARITHMETIC / f"{harness}-sum-unsupported",
    )
    answer = TrialView.load(tool_dir).final_answer
    assert answer == TrialView.load(prose_dir).final_answer
    assert "Rs 27,329.76" in answer

    with_add = json.loads((tool_dir / "checks.json").read_text(encoding="utf-8"))
    total = next(a for a in with_add["amounts"] if a["text"] == "Rs 27,329.76")
    assert total["supported_by"] == "tool"
    assert total["match"] == {
        "value": 27329.76,
        "where": "tool:add",
        "how": "exact",
        "precision": 0.01,
        "call": 2,
    }
    assert with_add["tools_called"] == ["calculate_emi", "list_debts", "add"]
    # D56: add's inputs are calculate_emi's EMI and list_debts' minimums, so its result counts.
    (added,) = with_add["arithmetic"]
    assert added["supported"] is True
    assert [i["match"]["where"] for i in added["inputs"]] == [
        "tool:calculate_emi",
        "tool:list_debts",
    ]

    prov, req = grade_trial(tool_dir, [PROVENANCE, REQUIRED])["grades"]
    assert prov["verdict"] == "pass", prov
    assert prov["reason"].startswith("0 of 3 amount(s)")
    assert req["verdict"] == "pass", req

    prov, req = grade_trial(prose_dir, [PROVENANCE, REQUIRED])["grades"]
    assert prov["verdict"] == "fail", prov
    assert "1 of 3 amount(s)" in prov["reason"] and "Rs 27,329.76" in prov["reason"]
    assert prov["evidence"] == [{"source": "final_answer", "quote": "Rs 27,329.76"}]
    assert req["verdict"] == "pass", req  # the same tools were required and called


def test_the_add_call_is_in_the_trace_under_the_harness_name():
    """Hermes calls it mcp__finance__add, the own loop add; the checks and graders read both."""
    names = {}
    for harness in HARNESSES:
        calls = TrialView.load(ARITHMETIC / f"{harness}-sum-tool").tool_calls()
        names[harness] = [(c.raw_name, c.arguments, c.result) for c in calls if c.name == "add"]
    added = ({"values": [8997.26, 18332.5]}, {"sum": 27329.76})
    assert names == {"ownloop": [("add", *added)], "hermes": [("mcp__finance__add", *added)]}
    added_spec = {"id": "added", "type": "tool_called", "tool": "add"}
    for harness in HARNESSES:
        called = grade_trial(ARITHMETIC / f"{harness}-sum-tool", [added_spec])["grades"][0]
        assert called["verdict"] == "pass", called
        absent = grade_trial(ARITHMETIC / f"{harness}-sum-unsupported", [added_spec])["grades"][0]
        assert absent["verdict"] == "fail", absent


@pytest.mark.parametrize("harness", HARNESSES)
def test_a_sum_worked_out_in_the_reply_and_passed_through_round_still_fails(harness):
    """D56: the same answer as with `add`, but the agent worked the sum out itself and passed it
    through round, which returns it unchanged. round's input has no source, so its result does
    not count and provenance fails on exactly that amount, saying why and quoting the call."""
    folder = ARITHMETIC / f"{harness}-sum-laundered"
    assert (
        TrialView.load(folder).final_answer
        == TrialView.load(ARITHMETIC / f"{harness}-sum-tool").final_answer
    )
    checks = json.loads((folder / "checks.json").read_text(encoding="utf-8"))
    total = next(a for a in checks["amounts"] if a["text"] == "Rs 27,329.76")
    assert (total["supported_by"], total["match"]) == (None, None)
    reason = "round's input 27,329.76 is not supported"
    assert total["rejected"] == {
        "value": 27329.76,
        "where": "tool:round",
        "how": "exact",
        "precision": 0.01,
        "call": 2,
        "reason": reason,
    }
    assert [(c["tool"], c["supported"], c["reason"]) for c in checks["arithmetic"]] == [
        ("round", False, reason)
    ]

    prov, req = grade_trial(folder, [PROVENANCE, REQUIRED])["grades"]
    assert prov["verdict"] == "fail", prov
    assert "1 of 3 amount(s)" in prov["reason"]
    assert f"Rs 27,329.76 ({reason})" in prov["reason"]
    raw = {"ownloop": "round", "hermes": "mcp__finance__round"}[harness]
    (call,) = [c for c in TrialView.load(folder).tool_calls() if c.raw_name == raw]
    assert prov["evidence"] == [
        {"source": "final_answer", "quote": "Rs 27,329.76"},
        {"source": "span", "span_id": call.span_id, "tool": "round", "quote": call.arguments_text},
    ]
    assert "27329.76" in call.arguments_text
    assert req["verdict"] == "pass", req


def test_a_checks_json_from_before_d56_cannot_decide_an_amount_from_an_arithmetic_tool(
    tmp_path,
):
    """The sum-tool trial as the runner wrote it before D56: no `arithmetic`, so whether add's
    inputs were supported is unknown, and with nothing else unsupported the grade is an error
    rather than a pass. The same folder with D56's checks passes."""
    old = tmp_path / "ownloop-sum-tool"
    shutil.copytree(ARITHMETIC / "ownloop-sum-tool", old)
    checks = json.loads((old / "checks.json").read_text(encoding="utf-8"))
    checks.pop("arithmetic")
    for row in checks["amounts"]:
        row.pop("rejected")
        row["match"].pop("call")
    (old / "checks.json").write_text(json.dumps(checks), encoding="utf-8")

    prov = grade_trial(old, [PROVENANCE])["grades"][0]
    assert prov["verdict"] == "error", prov
    assert "predates D56" in prov["reason"] and "Rs 27,329.76" in prov["reason"]
    assert {"source": "final_answer", "quote": "Rs 27,329.76"} in prov["evidence"]
    assert grade_trial(ARITHMETIC / "ownloop-sum-tool", [PROVENANCE])["grades"][0]["verdict"] == (
        "pass"
    )
    # The 4 Nov gate fixtures predate D56 too, but no amount rests on an arithmetic tool there.
    assert grades("ownloop-emi", PROVENANCE)[0]["verdict"] == "pass"


